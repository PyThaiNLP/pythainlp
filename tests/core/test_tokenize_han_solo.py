class _FakeTagger:
    def tag(self, features: list[Any]) -> list[str]:
        return ["1" if i % 2 == 0 else "0" for i in range(len(features))]


class HanSoloFeaturizerTestCase(unittest.TestCase):
    def test_featurize_golden(self) -> None:
        for args, expected in _GOLDEN:
            n, size, delimiter, sentence, padding, indiv, rtype = args
            with self.subTest(args=args):
                featurizer = han_solo.Featurizer(n, size, delimiter)
                try:
                    got = [
                        "ok",
                        featurizer.featurize(sentence, padding, indiv, rtype),
                    ]
                except Exception as ex:  # noqa: BLE001 - records any error
                    got = ["exc", type(ex).__name__, str(ex)]
                self.assertEqual(got, expected)

    def test_pad(self) -> None:
        featurizer = han_solo.Featurizer(2, 1)
        self.assertEqual(featurizer.pad("กข"), "###กข###")
        self.assertEqual(featurizer.pad("กข", "*"), "***กข***")

    def test_featurize_unpadded(self) -> None:
        featurizer = han_solo.Featurizer(2, 1)
        self.assertEqual(featurizer.featurize("กขคง", padding=False)["X"], [])
        feats = featurizer.featurize("กขคงจฉช", padding=False)
        self.assertEqual(len(feats["X"]), 2)
        self.assertEqual(feats["Y"], ["0", "0"])

    def test_segment_with_fake_tagger(self) -> None:
        with mock.patch.object(
            han_solo, "_get_tagger", return_value=_FakeTagger()
        ):
            self.assertEqual(han_solo.segment("กขคง"), ["กข", "คง"])
            self.assertEqual(han_solo.segment("ก"), ["ก"])
            self.assertEqual(han_solo.segment(""), [])


class HanSoloTaggerTestCase(unittest.TestCase):
    def test_get_tagger_loads_once(self) -> None:
        with mock.patch.multiple(
            han_solo,
            _tagger=None,
            _model_file_ctx=None,
            CRFTagger=mock.DEFAULT,
            as_file=mock.DEFAULT,
        ) as mocks:
            crf, as_file = mocks["CRFTagger"], mocks["as_file"]
            as_file.return_value.__enter__.return_value = "/model/path"
            tagger = han_solo._get_tagger()
            self.assertIs(tagger, crf.return_value)
            tagger.open.assert_called_once_with("/model/path")
            self.assertIs(han_solo._get_tagger(), tagger)
            crf.assert_called_once_with()

    def test_import_without_pycrfsuite(self) -> None:
        spec = importlib.util.spec_from_file_location(
            "han_solo_no_crf", str(han_solo.__file__)
        )
        if spec is None or spec.loader is None:
            self.fail("cannot load han_solo.py")
        module = importlib.util.module_from_spec(spec)
        with mock.patch.dict(sys.modules, {"pycrfsuite": None}):
            spec.loader.exec_module(module)
        self.assertIs(module.CRFTagger, han_solo.CRFTagger)


