class NewmmGoldenTestCase(unittest.TestCase):
    def test_segment_golden(self):
        for text, dict_name, safe, expected in _GOLDEN:
            with self.subTest(text=text[:30], dict=dict_name, safe=safe):
                trie = Trie(_DICTS[dict_name])
                self.assertEqual(expected[0], "ok")
                self.assertEqual(
                    newmm.segment(text, trie, safe_mode=safe), expected[1]
                )

    def test_segment_joins_back(self):
        trie = Trie(_DICT_A)
        text = "ผมกินข้าวabc 123 ที่บ้านใหญ่\nไทย" * 12
        for safe in (False, True):
            with self.subTest(safe=safe):
                tokens = newmm.segment(text, trie, safe_mode=safe)
                self.assertEqual("".join(tokens), text)

    def test_segment_empty_and_wrong_type(self):
        trie = Trie(_DICT_A)
        for value in (None, "", 123, b"abc", ["ก"], 1.5):
            with self.subTest(value=value):
                self.assertEqual(newmm.segment(value, trie), [])  # type: ignore[arg-type]

    def test_segment_empty_custom_dict_uses_default(self):
        # An empty Trie is falsy, so the default dictionary is used.
        self.assertEqual(newmm.segment("abc 1", Trie([])), ["abc", " ", "1"])

    def test_graph_size_cutoff(self):
        # More than _MAX_GRAPH_SIZE candidate words at one position.
        trie = Trie(["ก" * n for n in range(1, 60)])
        text = "ก" * 200
        for safe in (False, True):
            with self.subTest(safe=safe):
                tokens = newmm.segment(text, trie, safe_mode=safe)
                self.assertEqual("".join(tokens), text)

    def test_onecut_is_lazy(self):
        gen = newmm._onecut("ผมกินข้าว", Trie(_DICT_A))
        self.assertEqual(next(gen), "ผม")
        self.assertEqual(list(gen), ["กิน", "ข้าว"])

    def test_bfs_paths_graph(self):
        graph: Any = defaultdict(list)
        graph[0] = [1, 2]
        graph[1] = [3]
        graph[2] = [3]
        paths = list(newmm._bfs_paths_graph(graph, 0, 3))
        self.assertEqual(paths, [[0, 1, 3], [0, 2, 3]])
        self.assertEqual(list(newmm._bfs_paths_graph(graph, 3, 0)), [])


