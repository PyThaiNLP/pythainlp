class NumToThaiwordFloatTestCase(unittest.TestCase):
    def test_golden(self) -> None:
        for value, expected in _GOLDEN:
            with self.subTest(value=repr(value)):
                if isinstance(expected, tuple):
                    with self.assertRaises(Exception) as ctx:
                        num_to_thaiword_float(value)  # type: ignore[arg-type]
                    self.assertEqual(
                        (type(ctx.exception).__name__, str(ctx.exception)),
                        expected,
                    )
                else:
                    self.assertEqual(
                        num_to_thaiword_float(value),  # type: ignore[arg-type]
                        expected,
                    )

    def test_docstring_examples(self) -> None:
        self.assertEqual(num_to_thaiword_float(123.45), "หนึ่งร้อยยี่สิบสามจุดสี่ห้า")
        self.assertEqual(num_to_thaiword_float(3.14159), "สามจุดหนึ่งสี่หนึ่งห้าเก้า")

    def test_whole_numbers_use_integer_reading(self) -> None:
        for value in (0, 1, 21, 101, 1000001, -5, 12.0, -7.0, 1e16, 10**20):
            with self.subTest(value=value):
                self.assertEqual(
                    num_to_thaiword_float(value), num_to_thaiword(int(value))
                )

    def test_sign_prefix(self) -> None:
        for value in (0.5, 1.25, 1e-05, 123456.789):
            with self.subTest(value=value):
                self.assertEqual(
                    num_to_thaiword_float(-value),
                    "ลบ" + num_to_thaiword_float(value),
                )

    def test_expand_exponent(self) -> None:
        for text, expected in (
            ("0.5", "0.5"),
            ("1e-05", "0.00001"),
            ("1.5e-07", "0.00000015"),
            ("1.234e-10", "0.0000000001234"),
            ("5e-324", "0." + "0" * 323 + "5"),
            # Exponent that is not produced by str(float) of a fraction
            ("1.5e+3", "1500"),
            ("1e+2", "100"),
            ("12.5e-1", "1.25"),
            ("1E-2", "0.01"),
        ):
            with self.subTest(text=text):
                self.assertEqual(_expand_exponent(text), expected)

    def test_result_without_decimal_point(self) -> None:
        # Defensive branch: str() of a non-integer float always has a point.
        with mock.patch(
            "pythainlp.util.numtoword._expand_exponent", return_value="12"
        ):
            self.assertEqual(num_to_thaiword_float(0.5), "สิบสอง")

    # BUG-LEDGER: numtoword-ed-duplicate
    def test_bug_ed_rule_applied_twice(self) -> None:
        # The "เอ็ด" rule exists in both the block and the whole-number
        # conversion. The result is correct today; the duplicate is only
        # redundant code in num_to_thaiword. This marker pins the
        # redundancy only. It keeps passing after the duplicate is removed.
        self.assertEqual(num_to_thaiword(11), "สิบเอ็ด")
        self.assertEqual(num_to_thaiword(1000001), "หนึ่งล้านเอ็ด")
        self.assertEqual(num_to_thaiword(1), "หนึ่ง")
        self.assertEqual(num_to_thaiword(1000000), "หนึ่งล้าน")
        self.assertEqual(num_to_thaiword(101), "หนึ่งร้อยเอ็ด")


