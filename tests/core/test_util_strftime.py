class _BadStrftime(datetime):
    """Datetime whose strftime() raises ValueError, as some platforms do."""

    def strftime(self, format: str) -> str:  # noqa: A002
        raise ValueError(f"bad directive {format}")


class _FixedStrftime(datetime):
    """Datetime whose strftime() returns a fixed string."""

    result = ""

    def strftime(self, format: str) -> str:  # noqa: A002
        return self.result


class ThaiStrftimeTestCase(unittest.TestCase):
    def test_type_hints_resolve(self) -> None:
        # datetime and Callable must stay runtime imports
        import pythainlp.util.strftime as module

        self.assertIn("fmt", typing.get_type_hints(thai_strftime))
        typing.get_type_hints(module)

    def test_golden(self) -> None:
        for fmt, expected in _GOLDEN:
            if os.name == "nt" and fmt in _NOT_ON_WINDOWS:
                continue
            for dt_obj, exp in zip(_DATETIMES, expected):
                with self.subTest(fmt=fmt, dt=dt_obj):
                    with warnings.catch_warnings():
                        warnings.simplefilter("error")
                        self.assertEqual(thai_strftime(dt_obj, fmt), exp)

    def test_golden_thaidigit(self) -> None:
        for fmt, expected in _GOLDEN_THAIDIGIT:
            for dt_obj, exp in zip(_DATETIMES, expected):
                with self.subTest(fmt=fmt, dt=dt_obj):
                    self.assertEqual(
                        thai_strftime(dt_obj, fmt, thaidigit=True), exp
                    )
                    self.assertEqual(thai_strftime(dt_obj, fmt, True), exp)

    def test_default_format(self) -> None:
        self.assertEqual(thai_strftime(_DATETIMES[1]), "9 มิ.ย. 62")

    def test_trailing_percent_and_extension(self) -> None:
        dt_obj = _DATETIMES[0]
        for fmt, expected in (
            ("%", "%"),
            ("abc%", "abc%"),
            ("%-", "-"),
            ("%E", "E"),
            ("%O", "O"),
            ("a%^", "a^"),
            ("%%", "%"),
            ("%-%", "%"),
            ("", ""),
        ):
            with self.subTest(fmt=fmt):
                self.assertEqual(thai_strftime(dt_obj, fmt), expected)

    def test_l10n_directives_match_helper(self) -> None:
        for dt_obj in _DATETIMES:
            for char in _NEED_L10N:
                with self.subTest(char=char, dt=dt_obj):
                    self.assertEqual(
                        _thai_strftime(dt_obj, char),
                        thai_strftime(dt_obj, f"%{char}"),
                    )

    def test_helper_falls_back_to_standard(self) -> None:
        self.assertEqual(_thai_strftime(_DATETIMES[0], "H"), "01")
        self.assertEqual(_thai_strftime(_DATETIMES[0], "M"), "40")

    def test_unsupported_directive_normalized(self) -> None:
        dt_obj = _FixedStrftime(2019, 6, 9)
        for result in ("", "%Q"):
            dt_obj.result = result
            with self.subTest(result=result):
                self.assertEqual(thai_strftime(dt_obj, "%Q"), "Q")
                self.assertEqual(thai_strftime(dt_obj, "%-Q"), "Q")
        dt_obj.result = "Q"
        self.assertEqual(thai_strftime(dt_obj, "%Q"), "Q")

    def test_value_error_warns_and_continues(self) -> None:
        dt_obj = _BadStrftime(2019, 6, 9)
        for fmt, expected in (("%Q", "Q"), ("%-Q", "Q"), ("a%Zb", "aZb")):
            with self.subTest(fmt=fmt):
                with warnings.catch_warnings(record=True) as caught:
                    warnings.simplefilter("always")
                    self.assertEqual(thai_strftime(dt_obj, fmt), expected)
                self.assertEqual(len(caught), 1)
                self.assertIs(caught[0].category, UserWarning)
                char = expected.replace("a", "").replace("b", "")
                self.assertEqual(
                    str(caught[0].message),
                    f"String format directive unknown/not support: %{char}\n"
                    f"The system raises this ValueError: bad directive %{char}\n"
                    "Continue working without the directive.",
                )

    def test_no_warning_for_known_directives(self) -> None:
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            thai_strftime(_DATETIMES[0], "%A %-d %B %Y %H:%M")
        self.assertEqual(caught, [])

    def test_invalid_input(self) -> None:
        with self.assertRaises(AttributeError):
            thai_strftime(None, "%A")  # type: ignore[arg-type]
        with self.assertRaises(AttributeError):
            thai_strftime(None, "%Y")  # type: ignore[arg-type]
        with self.assertRaises(TypeError):
            thai_strftime(_DATETIMES[0], None)  # type: ignore[arg-type]
        with self.assertRaises(TypeError):
            thai_strftime(_DATETIMES[0], 5)  # type: ignore[arg-type]
        # Without directives the datetime is never used
        self.assertEqual(thai_strftime(None, "abc"), "abc")  # type: ignore[arg-type]


